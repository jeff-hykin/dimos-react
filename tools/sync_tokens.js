#!/usr/bin/env -S deno run --allow-all
// Regenerates src/theme/tokens.js (the off-Desktop fallback) from Desktop's /theme.css: a URL or a file path.
const from = Deno.args[0] ?? "http://localhost:5555/theme.css"
const css = /^https?:/.test(from) ? await (await fetch(from)).text() : Deno.readTextFileSync(from)
// fonts are Desktop's own files; off Desktop the system fallbacks in the font tokens apply
const tokens = css.replace(/@font-face\s*\{[^}]*\}\s*/g, "")
const skins = [...new Set([...tokens.matchAll(/data-skin="([\w-]+)"/g)].map((match) => match[1]))]
const out = `// Desktop's theme tokens (every skin), generated by tools/sync_tokens.js from ${
    from.replace(/^\/Users\/[^/]+/, "~")
}.
// Used only off Desktop; on Desktop the provider links Desktop's own /theme.css instead.
export const SKINS = ${JSON.stringify(["portal", ...skins])}

export const TOKENS_CSS = ${JSON.stringify(tokens)}
`
Deno.writeTextFileSync("src/theme/tokens.js", out)
console.log("skins:", ["portal", ...skins].join(", "))
