// The .d.ts text for one entry module: components (capitalized functions) take any props and return a React node,
// hooks and helpers take and return anything, classes are constructible, everything else is `any`.
const HEADER = (entry) =>
    `// Generated by tools/types.js from ${entry}.js (deno task types). Loose types: names are checked, props are not.\n// deno-lint-ignore-file no-explicit-any\n`

/** @param {string} entry @param {Record<string, unknown>} module */
export function declarations(entry, module) {
    const lines = [HEADER(entry), 'import type { ReactNode } from "react"', ""]
    for (const name of Object.keys(module).sort()) {
        const value = module[name]
        const isClass = typeof value === "function" && /^class[\s{]/.test(Function.prototype.toString.call(value))
        if (isClass) {
            lines.push(`export declare const ${name}: any`, `export type ${name} = any`)
        } else if (typeof value === "function" && /^[A-Z]/.test(name)) {
            lines.push(`export declare function ${name}(props: Record<string, any>): ReactNode`)
        } else if (typeof value === "function") {
            lines.push(`export declare const ${name}: ((...args: any[]) => any) & Record<string, any>`)
        } else {
            lines.push(`export declare const ${name}: any`)
        }
    }
    return lines.join("\n") + "\n"
}
